import { cp, mkdir, readFile, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'dist', 'local.tux.yamusic.sdPlugin');
await mkdir(output, { recursive: true });
await cp(path.join(root, 'plugin'), output, { recursive: true });
execFileSync('pwsh', ['-NoProfile', '-File', path.join(root, 'scripts', 'build-icons.ps1')], { cwd: root, stdio: 'inherit' });
await cp(path.join(root, 'src'), path.join(output, 'bin'), { recursive: true });
await mkdir(path.join(output, 'bin', 'node_modules'), { recursive: true });
await cp(path.join(root, 'node_modules', 'ws'), path.join(output, 'bin', 'node_modules', 'ws'), { recursive: true });
execFileSync('dotnet', ['publish', 'native/AudioBridge/AudioBridge.csproj', '-c', 'Release', '-r', 'win-x64', '--self-contained', 'true', '-p:PublishSingleFile=true', '-p:IncludeNativeLibrariesForSelfExtract=true', '-o', path.join(output, 'bin', 'native')], { cwd: root, stdio: 'inherit' });
await access(path.join(output, 'bin', 'native', 'AudioBridge.exe'));
execFileSync('dotnet', ['publish', 'native/WindowCapture/WindowCapture.csproj', '-c', 'Release', '-r', 'win-x64', '--self-contained', 'true', '-p:PublishSingleFile=true', '-p:IncludeNativeLibrariesForSelfExtract=true', '-o', path.join(output, 'bin', 'native')], { cwd: root, stdio: 'inherit' });
await access(path.join(output, 'bin', 'native', 'WindowCapture.exe'));
execFileSync('pwsh', ['-NoProfile', '-File', path.join(root, 'scripts', 'make-music-profile.ps1')], { cwd: root, stdio: 'inherit' });
const manifest = JSON.parse(await readFile(path.join(output, 'manifest.json'), 'utf8'));
await writeFile(path.join(root, 'dist', 'build-info.json'), JSON.stringify({ version: manifest.Version, created: new Date().toISOString() }, null, 2));
console.log(`Built ${output}`);
